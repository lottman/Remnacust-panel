export function variableLocales(name) {
    if (variableGroups[name]) return variableGroups[name]
    if (!name.startsWith('TRAFFICLOCATION'))
        throw new Error(`Missing variable translation: ${name}`)
    const tag = name.endsWith('TEG')
    const faContext = tag ? 'سهمیه تگ با برگشت به هاست در نبود تگ' : 'هاست'
    const zhContext = tag ? '标签配额，无标签则回退至主机' : '主机'
    const listFa = ' بدون هاست فعلی فهرست «نام: مقدار» می‌دهد.'
    const listZh = ' 无当前主机时返回“名称：值”列表。'
    if (name.includes('RESETAT'))
        return {
            fa: `بازنشانی بعدی در UTC؛ format=… نمایش را تغییر می‌دهد و نبود بازنشانی ∞ است. زمینه ${faContext}.${listFa}`,
            zh: `下次重置时间使用 UTC，format=… 修改显示，未设置重置时为 ∞。使用${zhContext}。${listZh}`
        }
    const faKind =
        name.includes('USED') || /USE(?:TEG)?$/.test(name)
            ? 'مصرف'
            : name.includes('LIMIT')
              ? 'سهمیه'
              : 'باقیمانده'
    const zhKind =
        name.includes('USED') || /USE(?:TEG)?$/.test(name)
            ? '已用流量'
            : name.includes('LIMIT')
              ? '配额'
              : '剩余配额'
    const unit = name.includes('MB') ? 'MB' : name.includes('GB') ? 'GB' : ''
    return {
        fa: `${faKind} ${faContext}.${unit ? ` برحسب ${unit} با پایه 1024، فقط عدد بدون واحد.` : listFa} سهمیه یا باقیمانده نامحدود ∞ است.`,
        zh: `${zhContext}的${zhKind}。${unit ? `使用 1024 基数的 ${unit}，仅输出数值，不带单位。` : listZh}不限量配额或剩余值为 ∞。`
    }
}
